"""Fetch daily weather observations for UK cities and store them in PostgreSQL."""

import os
from datetime import datetime, timedelta, timezone
from typing import Any

import psycopg2
import requests
from airflow import DAG
from airflow.operators.python import PythonOperator


OPENWEATHER_URL = "https://api.openweathermap.org/data/2.5/weather"
REQUEST_TIMEOUT_SECONDS = 30

CITIES = [
    {"name": "London", "lat": 51.5074, "lon": -0.1278},
    {"name": "Birmingham", "lat": 52.4862, "lon": -1.8904},
    {"name": "Manchester", "lat": 53.4808, "lon": -2.2426},
    {"name": "Glasgow", "lat": 55.8642, "lon": -4.2518},
    {"name": "Liverpool", "lat": 53.4084, "lon": -2.9916},
    {"name": "Leeds", "lat": 53.8008, "lon": -1.5491},
    {"name": "Sheffield", "lat": 53.3811, "lon": -1.4701},
    {"name": "Bristol", "lat": 51.4545, "lon": -2.5879},
    {"name": "Newcastle", "lat": 54.9784, "lon": -1.6174},
    {"name": "Nottingham", "lat": 52.9548, "lon": -1.1581},
]


def fetch_weather(city: dict[str, Any], api_key: str) -> dict[str, Any]:
    """Fetch and normalize the latest observation for one city."""
    response = requests.get(
        OPENWEATHER_URL,
        params={
            "lat": city["lat"],
            "lon": city["lon"],
            "appid": api_key,
            "units": "metric",
        },
        timeout=REQUEST_TIMEOUT_SECONDS,
    )
    response.raise_for_status()
    data = response.json()

    return {
        "city": city["name"],
        "temperature": float(data["main"]["temp"]),
        "humidity": int(data["main"]["humidity"]),
        "weather_description": str(data["weather"][0]["description"]),
        "weather_date": datetime.fromtimestamp(data["dt"], tz=timezone.utc).date(),
    }


def store_weather(observations: list[dict[str, Any]]) -> None:
    """Create or upgrade the target table and upsert the observations."""
    connection = psycopg2.connect(
        host=os.environ.get("POSTGRES_HOST", "postgres"),
        port=int(os.environ.get("POSTGRES_PORT", "5432")),
        dbname=os.environ["POSTGRES_DB"],
        user=os.environ["POSTGRES_USER"],
        password=os.environ["POSTGRES_PASSWORD"],
        connect_timeout=10,
    )
    try:
        with connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    CREATE TABLE IF NOT EXISTS public.weather (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        city VARCHAR(50) NOT NULL,
                        temperature DOUBLE PRECISION NOT NULL,
                        humidity INTEGER,
                        weather_description TEXT,
                        weather_date DATE NOT NULL
                    )
                    """
                )
                cursor.execute(
                    """
                    SELECT is_identity
                    FROM information_schema.columns
                    WHERE table_schema = 'public'
                      AND table_name = 'weather'
                      AND column_name = 'id'
                    """
                )
                id_is_identity = cursor.fetchone()[0] == "YES"
                if not id_is_identity:
                    cursor.execute(
                        """
                        ALTER TABLE public.weather
                        ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY
                        """
                    )

                cursor.execute(
                    """
                    CREATE UNIQUE INDEX IF NOT EXISTS weather_city_date_key
                    ON public.weather (city, weather_date)
                    """
                )
                cursor.executemany(
                    """
                    INSERT INTO public.weather (
                        city, temperature, humidity, weather_description, weather_date
                    )
                    VALUES (%(city)s, %(temperature)s, %(humidity)s,
                            %(weather_description)s, %(weather_date)s)
                    ON CONFLICT (city, weather_date) DO UPDATE SET
                        temperature = EXCLUDED.temperature,
                        humidity = EXCLUDED.humidity,
                        weather_description = EXCLUDED.weather_description
                    """,
                    observations,
                )
    finally:
        connection.close()


def run_weather_etl() -> dict[str, int]:
    """Fetch weather for all configured cities and store it in PostgreSQL."""
    api_key = os.environ.get("OPENWEATHER_API_KEY", "").strip()
    if not api_key:
        raise RuntimeError(
            "OPENWEATHER_API_KEY is not set. Add your OpenWeatherMap API key "
            "to the project's .env file, then restart the Airflow services."
        )

    observations = [fetch_weather(city, api_key) for city in CITIES]
    store_weather(observations)
    return {"cities_processed": len(observations)}


with DAG(
    dag_id="weather_etl",
    description="Fetch daily weather observations for UK cities into PostgreSQL",
    start_date=datetime(2024, 1, 1, tzinfo=timezone.utc),
    schedule="@daily",
    catchup=False,
    default_args={
        "owner": "data-engineering",
        "retries": 2,
        "retry_delay": timedelta(minutes=5),
    },
    tags=["weather", "etl"],
) as dag:
    fetch_and_store_weather = PythonOperator(
        task_id="fetch_and_store_weather",
        python_callable=run_weather_etl,
    )
